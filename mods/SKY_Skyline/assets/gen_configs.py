def tower_config():
    model = lambda c: S.PREFIX_TOWER + "\\" + S.P3D[c]
    stops = S.elevator_stops()
    C = S.CORE
    d = S.KEYCARD_DOOR
    out = HEADER + patches("SKY_Skyline_TowerA", ["DZ_Data", "SKY_Skyline_Textures", "SKY_Skyline_Scripts"])
    out += "\nclass CfgVehicles\n{\n\tclass HouseNoDestruct;\n"
    out += "\tclass Land_SKY_TowerA_Base: HouseNoDestruct\n\t{\n\t\tscope = 0;\n\t};\n"
    for c in (S.CLASS_FLOOR, S.CLASS_ROOF):
        out += "\tclass %s: Land_SKY_TowerA_Base\n\t{\n\t\tscope = 1;\n\t\tmodel = \"%s\";\n\t};\n" % (c, model(c))
    # Lobby: keycard door (doors-on-buildings pattern from Test_Building).
    out += """\tclass %s: Land_SKY_TowerA_Base
\t{
\t\tscope = 1;
\t\tmodel = "%s";
\t\tclass Doors
\t\t{
\t\t\tclass %s
\t\t\t{
\t\t\t\tdisplayName = "Security door";
\t\t\t\tcomponent = "%s";
\t\t\t\tsoundPos = "%s_action";
\t\t\t\tanimPeriod = 1.0;
\t\t\t\tinitPhase = 0.0;
\t\t\t\tinitOpened = 0.0;
\t\t\t\tsoundOpen = "doorMetalSmallOpen";
\t\t\t\tsoundClose = "doorMetalSmallClose";
\t\t\t\tsoundLocked = "doorMetalSmallRattle";
\t\t\t\tsoundOpenABit = "doorMetalSmallOpenABit";
\t\t\t};
\t\t};
\t\t// SKY keycard doors: Doors class names + required tier (read by script class Land_SKY_TowerA_Lobby).
\t\tskyKeycardDoors[] = {"%s"};
\t\tskyKeycardTiers[] = {%d};
\t\tskyKeycardRelockMs = %d;
\t\t// Security room interior, model space {x0, x1, z0, z1} (exit button works only inside).
\t\tskySecurityRoom[] = {%g, %g, %g, %g};
%s\t};
""" % (S.CLASS_LOBBY, model(S.CLASS_LOBBY), d["name"], d["name"], d["name"], d["name"], d["required_tier"],
       d["relock_ms"], S.SECURITY_ROOM["x"][0] + S.WALL_T / 2, S.SECURITY_ROOM["x"][1],
       S.SECURITY_ROOM["y"][0] + S.WALL_T / 2, S.SECURITY_ROOM["y"][1], damage_system_static([d["name"]]))
    # Core: elevator (user animation sources, script-driven).
    src = ""
    for i in range(len(stops)):
        src += "\t\t\tclass elev_door_l%d\n\t\t\t{\n\t\t\t\tsource = \"user\";\n\t\t\t\tanimPeriod = 1.2;\n\t\t\t\tinitPhase = 0;\n\t\t\t};\n" % i
    out += """\tclass %s: Land_SKY_TowerA_Base
\t{
\t\tscope = 1;
\t\tmodel = "%s";
\t\tclass AnimationSources
\t\t{
%s\t\t};
\t\t// SKY elevator parameters (read by script class Land_SKY_TowerA_Core).
\t\tskyStops[] = {%s};
\t\tskyMaxOccupants = %d;
\t\tskyCooldownMs = %d;
\t\tskyDoorOpenMs = %d;
\t\tskyTravelMsBase = %d;
\t\tskyTravelMsPerStop = %d;
\t\tskyCabHalfX = %g;
\t\tskyCabHalfY = %g;
\t\tskyCabHeight = %g;
\t\tskyPanelReach = 1.6;
\t};
};
""" % (S.CLASS_CORE, model(S.CLASS_CORE), src, ", ".join("%g" % s for s in stops), C["max_occupants"],
       C["cooldown_ms"], C["door_open_ms"], C["travel_ms_base"], C["travel_ms_per_stop"],
       (C["cab_x"][1] - C["cab_x"][0]) / 2, (C["elev_y"][1] - S.WALL_T - C["elev_y"][0]) / 2, C["cab_h"])
    return out


