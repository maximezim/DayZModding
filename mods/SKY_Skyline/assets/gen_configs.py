def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    stale = []
    for rel, text in outputs().items():
        path = os.path.join(ADDONS, rel.replace("/", os.sep))
        text = text.replace("\r\n", "\n")
        cur = open(path, encoding="utf-8").read().replace("\r\n", "\n") if os.path.exists(path) else None
        if cur != text:
            stale.append(rel)
            if not a.check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\r\n") as fh:
                    fh.write(text)
    if a.check and stale:
        print("stale generated files:", ", ".join(stale))
        sys.exit(1)
    print("up to date" if not stale else "wrote: " + ", ".join(stale))


if __name__ == "__main__":
    main()
