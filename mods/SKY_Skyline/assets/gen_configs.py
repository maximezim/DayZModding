#!/usr/bin/env python3
"""Generate config.cpp / model.cfg / rvmat files for SKY_Skyline from skyspec.

    python mods/SKY_Skyline/assets/gen_configs.py            # writes into addons/
    python mods/SKY_Skyline/assets/gen_configs.py --check    # exit 1 if files are stale

Outputs are committed (reviewable diffs); re-run after editing skyspec.py.
Syntax follows Bohemia's DayZ-Samples (Test_Building config.cpp/model.cfg,
Test_ClothingRetexture hiddenSelections) - see SLICE_REPORT.md for sources.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import skyspec as S  # noqa: E402

ADDONS = os.path.join(os.path.dirname(HERE), "addons")
HEADER = "// GENERATED by assets/gen_configs.py from assets/skyspec.py - do not edit by hand.\n"


def patches(name, required):
    req = ", ".join('"%s"' % r for r in required)
    return ("class CfgPatches\n{\n\tclass %s\n\t{\n\t\tunits[] = {};\n\t\tweapons[] = {};\n"
            "\t\trequiredVersion = 0.1;\n\t\trequiredAddons[] = {%s};\n\t};\n};\n" % (name, req))


# ------------------------------------------------------------------ rvmat
UVT = ("\tclass uvTransform\n\t{\n\t\taside[] = {1, 0, 0};\n\t\tup[] = {0, 1, 0};\n"
       "\t\tdir[] = {0, 0, 1};\n\t\tpos[] = {0, 0, 0};\n\t};\n")


def stage(n, texture, uv_source="tex", extra=""):
    body = '\ttexture = "%s";\n\tuvSource = "%s";\n' % (texture, uv_source)
    if uv_source == "tex":
        body += UVT
    return "class Stage%d\n{\n%s%s};\n" % (n, body, extra)


def rvmat_super(base, spec_power=40, emissive=(0, 0, 0)):
    """Standard 'Super' shader layout (Stage1 nohq, 2 detail, 3 macro, 4 as,
    5 smdi, 6 fresnel, 7 env). Detail/macro are neutral procedurals."""
    d = S.PREFIX_TEX + "\\data\\" + base
    out = HEADER
    out += "ambient[] = {1, 1, 1, 1};\ndiffuse[] = {1, 1, 1, 1};\nforcedDiffuse[] = {0, 0, 0, 0};\n"
    out += "emmisive[] = {%g, %g, %g, 1};\nspecular[] = {0.7, 0.7, 0.7, 1};\nspecularPower = %d;\n" % (
        emissive + (spec_power,))
    out += 'PixelShaderID = "Super";\nVertexShaderID = "Super";\n'
    out += stage(1, d + "_nohq.paa")
    out += stage(2, "#(argb,8,8,3)color(0.5,0.5,0.5,1,DT)")
    out += stage(3, "#(argb,8,8,3)color(0,0,0,0,MC)")
    out += stage(4, d + "_as.paa")
    out += stage(5, d + "_smdi.paa")
    out += stage(6, "#(ai,64,64,1)fresnel(1.5,0.8)", "none")
    # Env map path follows the vanilla convention; confirmed by Check-SkyAssets.ps1 on P:.
    out += stage(7, "dz\\data\\data\\env_land_co.paa", "none", '\tuseWorldEnvMap = "true";\n')
    return out


RVMATS = {
    "sky_concrete": ("sky_concrete", 20), "sky_metal": ("sky_metal", 60), "sky_glass": ("sky_glass", 120), "sky_glassfar": ("sky_glassfar", 80),
    "sky_tile": ("sky_tile", 50), "sky_carpet": ("sky_carpet", 5), "sky_wallpaper": ("sky_wallpaper", 10),
    "sky_roofmark": ("sky_roofmark", 15), "sky_asphalt": ("sky_asphalt", 10),
}


# ------------------------------------------------------------------ tower config
