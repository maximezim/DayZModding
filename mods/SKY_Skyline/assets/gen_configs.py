def city_lit_script():
    """Script classes for the intact city buildings: night lights at light_1 / light_4
    (SKY_LitBuilding, D55). Damaged and ruined buildings stay dark (plain House)."""
    out = ("// GENERATED by assets/gen_configs.py from skyspec.KIT (city buildings, D56) - do not edit.\n"
           "// Intact buildings light up at night; offices / civic / industrial use the cool office light.\n")
    for name, e in sorted(S.KIT.items()):
        c = e.get("city")
        if not c or c["ruin"] != 0 or not c.get("archetype") or S.CITY_ARCHETYPES[c["archetype"]].get("special"):
            continue                                       # lots, kit pieces, substations: no lights
        group = S.CITY_ARCHETYPES[c["archetype"]]["group"]
        body = ""
        if group in ("commercial", "civic", "industrial"):
            body = "\n\toverride protected typename SkyLightType()\n\t{\n\t\treturn SKY_OfficeLight;\n\t}\n"
        out += "\nclass %s extends SKY_LitBuilding\n{%s}\n" % (e["cls"], body)
    return out


